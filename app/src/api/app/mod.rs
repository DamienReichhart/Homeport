/// The app's name, as its window and its packages show it.
const NAME: &str = "Homeport";

#[derive(Debug, Serialize)]
pub struct AppInfo {
    pub name: String,
    pub version: String,
    pub os: &'static str,
    pub arch: &'static str,
}

pub fn get_app_info() -> AppInfo {
    AppInfo {
        name: NAME.to_owned(),
        version: env!("CARGO_PKG_VERSION").to_owned(),
        os: std::env::consts::OS,
        arch: std::env::consts::ARCH,
    }
}

/// Why Homeport couldn't start, if it couldn't: the window then shows this
/// instead of the app, and no other use case works.
pub fn startup_problem(startup: &Startup) -> Option<StartupProblem> {
    startup.0.clone()
}

/// Opens the folder holding Homeport's database in the file manager. `open`
/// shows a folder there; the dialogs and opener layer (#253) supplies it.
pub fn open_data_folder(
    state: &AppState,
    open: impl FnOnce(&Path) -> io::Result<()>,
) -> AppResult<()> {
    let dir = &state.data_dir;
    local_files::ensure_folder(dir)?;
    open(dir).map_err(|e| local_files::folder_not_opened(dir, &e))
}

/// The OS's entry that starts Homeport when the user logs in: a Launch Agent
/// on macOS, the `Run` key on Windows, an XDG autostart entry on Linux. The
/// window and autostart layer (#252) implements it.
pub trait LoginEntry {
    /// Whether the entry is there, as the OS has it now.
    fn is_enabled(&self) -> io::Result<bool>;
    fn enable(&self) -> io::Result<()>;
    fn disable(&self) -> io::Result<()>;
}

/// Reading or writing the entry that starts Homeport at login failed.
fn autostart(e: io::Error) -> AppError {
    AppError::new(ErrorCode::AutostartFailed, msg::AUTOSTART_FAILED)
        .with_hint(msg::AUTOSTART_FAILED_HINT)
        .with_cause(&e)
}

/// Whether Homeport starts when the user logs in, read from the OS each
/// time, so removing the entry by hand shows here.
pub fn app_start_at_login(login: &impl LoginEntry) -> AppResult<bool> {
    login.is_enabled().map_err(autostart)
}

/// Adds or removes the login entry; returns whether it's there now.
pub fn app_set_start_at_login(login: &impl LoginEntry, enabled: bool) -> AppResult<bool> {
    if enabled {
        login.enable()
    } else {
        login.disable()
    }
    .map_err(autostart)?;
    app_start_at_login(login)
}

#[derive(Debug, Serialize)]
pub struct Licenses {
    /// Homeport's own license (`LICENSE`).
    pub app: &'static str,
    /// Every bundled crate and npm package with its license. Generated by
    /// `bun run licenses` before release builds, so other builds may lack it.
    pub third_party: Option<String>,
}

/// `resource_dir` is the folder the packages install Homeport's bundled
/// files to; the startup layer (#254) knows where it is.
pub fn get_licenses(resource_dir: &Path) -> AppResult<Licenses> {
    let path = resource_dir.join("licenses/THIRD_PARTY_LICENSES.txt");
    let third_party = match std::fs::read_to_string(path) {
        Ok(text) => Some(text),
        Err(e) if e.kind() == io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.into()),
    };
    Ok(Licenses {
        app: include_str!("../../../../LICENSE"),
        third_party,
    })
}

/// What this machine can do; features degrade gracefully when something is missing.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Capabilities {
    /// An OS keychain is reachable, so SSH, TLS, stack `.env` and registry secrets can be stored.
    pub keychain: bool,
    /// The keychain has no entry for the key the stored secrets were sealed
    /// with, and Homeport made no new one over them: `keychain_start_over`.
    pub keychain_entry_missing: bool,
    /// Whether Managed Stacks can be deployed here.
    pub compose: ComposeSupport,
    /// Whether Stacks can be deployed to a Swarm from here: the `docker`
    /// CLI, for `docker stack deploy` (ADR 0017).
    pub stack_deploy: ComposeSupport,
    /// Whether Synced Stacks can be cloned and fetched here.
    pub git: GitSupport,
    /// Whether Helm releases can be managed from here (ADR 0009).
    pub helm: HelmSupport,
    /// Homeport has an icon in the system tray, so closing the window can
    /// keep it running there.
    pub tray: bool,
}

/// The git CLI Synced Stacks use, or why there's none.
#[derive(Debug, Serialize)]
#[serde(
    tag = "state",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum GitSupport {
    Available {
        cli: GitCli,
    },
    /// `problem` says how to install it.
    Unavailable {
        problem: AppError,
    },
}

/// The helm CLI Helm releases are managed with, or why there's none.
#[derive(Debug, Serialize)]
#[serde(
    tag = "state",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum HelmSupport {
    Available {
        cli: HelmCli,
    },
    /// `problem` says how to install it.
    Unavailable {
        problem: AppError,
    },
}

/// The compose CLI used to deploy Managed Stacks, or why there's none.
#[derive(Debug, Serialize)]
#[serde(
    tag = "state",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum ComposeSupport {
    Available {
        cli: ComposeCli,
    },
    /// `problem` says what's missing and how to install it.
    Unavailable {
        problem: AppError,
    },
}

/// `tray` is whether this desktop shows Homeport's tray icon, which the tray
/// layer (#250) knows.
pub async fn get_capabilities(state: &AppState, tray: bool) -> Capabilities {
    Capabilities {
        keychain: state.secrets.is_available(),
        keychain_entry_missing: state.secrets.entry_missing(),
        compose: match compose::detect().await {
            Ok(cli) => ComposeSupport::Available { cli },
            Err(problem) => ComposeSupport::Unavailable { problem },
        },
        stack_deploy: match compose::stack::detect().await {
            Ok(cli) => ComposeSupport::Available { cli },
            Err(problem) => ComposeSupport::Unavailable { problem },
        },
        git: match git::detect().await {
            Ok(cli) => GitSupport::Available { cli },
            Err(problem) => GitSupport::Unavailable { problem },
        },
        helm: match helm::detect().await {
            Ok(cli) => HelmSupport::Available { cli },
            Err(problem) => HelmSupport::Unavailable { problem },
        },
        tray,
    }
}

/// Gives up on the key the stored secrets were sealed with, whose keychain
/// entry is missing: uses the entry if it came back, or stores a new key.
/// Secrets sealed under the old key then show as lost, to re-enter or
/// restore from a backup. Refused while the keychain's key works.
pub async fn keychain_start_over(state: &AppState) -> AppResult<()> {
    let secrets = state.secrets.clone();
    // Keychain backends may block on D-Bus; keep that off the async runtime.
    tokio::task::spawn_blocking(move || secrets.start_over(&crate::app::setup::KEYCHAIN))
        .await
        .expect("keychain task panicked")?;
    state.hosts.registry.reload()?;
    state.clusters.registry.reload()?;
    Ok(())
}

/// Reads a file the user picked in an open dialog (certificates, keys, compose files).
pub fn read_text_file(path: String) -> AppResult<String> {
    local_files::read_text(Path::new(&path))
}

/// Opens the folder holding Homeport's log files in the file manager.
/// `log_dir` is where the logging layer (#254) writes them; `open` shows a
/// folder in the file manager (#253).
pub fn open_log_folder(
    log_dir: &Path,
    open: impl FnOnce(&Path) -> io::Result<()>,
) -> AppResult<()> {
    local_files::ensure_folder(log_dir)?;
    open(log_dir).map_err(|e| local_files::folder_not_opened(log_dir, &e))
}

/// Writes text to a path the user picked in a save dialog (e.g. downloaded logs).
pub fn write_text_file(path: String, contents: String) -> AppResult<()> {
    local_files::write_text(Path::new(&path), &contents)
}
