//! Homeport itself: what it is, what this computer lets it do, and the files
//! the user picks in its dialogs.

use std::path::Path;

use serde::Serialize;
use tauri::{AppHandle, Manager, State};

use homeport_clusters::helm::{self, HelmCli};
use homeport_core::local_files;
use homeport_git::{cli as git, GitCli};
use homeport_stacks::compose::{self, ComposeCli};

use crate::{
    app::AppState,
    error::{self, AppError, AppResult},
};

#[derive(Debug, Serialize, specta::Type)]
pub struct AppInfo {
    name: String,
    version: String,
    os: &'static str,
    arch: &'static str,
}

#[tauri::command]
#[specta::specta]
pub fn get_app_info(app: AppHandle) -> AppInfo {
    let info = app.package_info();
    AppInfo {
        name: info.name.clone(),
        version: info.version.to_string(),
        os: std::env::consts::OS,
        arch: std::env::consts::ARCH,
    }
}

/// Whether Homeport starts when the user logs in, read from the OS each
/// time, so removing the entry by hand shows here.
#[tauri::command]
#[specta::specta]
pub fn app_start_at_login(app: AppHandle) -> AppResult<bool> {
    crate::app::autostart::is_enabled(&app)
}

/// Adds or removes the login entry; returns whether it's there now.
#[tauri::command]
#[specta::specta]
pub fn app_set_start_at_login(app: AppHandle, enabled: bool) -> AppResult<bool> {
    crate::app::autostart::set_enabled(&app, enabled)
}

#[derive(Debug, Serialize, specta::Type)]
pub struct Licenses {
    /// Homeport's own license (`LICENSE`).
    app: &'static str,
    /// Every bundled crate and npm package with its license. Generated by
    /// `bun run licenses` before release builds, so other builds may lack it.
    third_party: Option<String>,
}

#[tauri::command]
#[specta::specta]
pub fn get_licenses(app: AppHandle) -> AppResult<Licenses> {
    let path = app
        .path()
        .resource_dir()
        .map_err(error::window)?
        .join("licenses/THIRD_PARTY_LICENSES.txt");
    let third_party = match std::fs::read_to_string(path) {
        Ok(text) => Some(text),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.into()),
    };
    Ok(Licenses {
        app: include_str!("../../../LICENSE"),
        third_party,
    })
}

/// What this machine can do; features degrade gracefully when something is missing.
#[derive(Debug, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct Capabilities {
    /// An OS keychain is reachable, so SSH, TLS, stack `.env` and registry secrets can be stored.
    keychain: bool,
    /// Whether Managed Stacks can be deployed here.
    compose: ComposeSupport,
    /// Whether Stacks can be deployed to a Swarm from here: the `docker`
    /// CLI, for `docker stack deploy` (ADR 0017).
    stack_deploy: ComposeSupport,
    /// Whether Synced Stacks can be cloned and fetched here.
    git: GitSupport,
    /// Whether Helm releases can be managed from here (ADR 0009).
    helm: HelmSupport,
    /// Homeport has an icon in the system tray, so closing the window can
    /// keep it running there.
    tray: bool,
}

/// The git CLI Synced Stacks use, or why there's none.
#[derive(Debug, Serialize, specta::Type)]
#[serde(
    tag = "state",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum GitSupport {
    Available {
        cli: GitCli,
    },
    /// `problem` says how to install it.
    Unavailable {
        problem: AppError,
    },
}

/// The helm CLI Helm releases are managed with, or why there's none.
#[derive(Debug, Serialize, specta::Type)]
#[serde(
    tag = "state",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum HelmSupport {
    Available {
        cli: HelmCli,
    },
    /// `problem` says how to install it.
    Unavailable {
        problem: AppError,
    },
}

/// The compose CLI used to deploy Managed Stacks, or why there's none.
#[derive(Debug, Serialize, specta::Type)]
#[serde(
    tag = "state",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum ComposeSupport {
    Available {
        cli: ComposeCli,
    },
    /// `problem` says what's missing and how to install it.
    Unavailable {
        problem: AppError,
    },
}

#[tauri::command]
#[specta::specta]
pub async fn get_capabilities(
    app: AppHandle,
    state: State<'_, AppState>,
) -> Result<Capabilities, ()> {
    Ok(Capabilities {
        keychain: state.secrets.is_available(),
        compose: match compose::detect().await {
            Ok(cli) => ComposeSupport::Available { cli },
            Err(problem) => ComposeSupport::Unavailable { problem },
        },
        stack_deploy: match compose::stack::detect().await {
            Ok(cli) => ComposeSupport::Available { cli },
            Err(problem) => ComposeSupport::Unavailable { problem },
        },
        git: match git::detect().await {
            Ok(cli) => GitSupport::Available { cli },
            Err(problem) => GitSupport::Unavailable { problem },
        },
        helm: match helm::detect().await {
            Ok(cli) => HelmSupport::Available { cli },
            Err(problem) => HelmSupport::Unavailable { problem },
        },
        tray: crate::app::tray::is_available(&app),
    })
}

/// Reads a file the user picked in an open dialog (certificates, keys, compose files).
#[tauri::command]
#[specta::specta]
pub fn read_text_file(path: String) -> AppResult<String> {
    local_files::read_text(Path::new(&path))
}

/// Opens the folder holding Homeport's log files in the file manager.
#[tauri::command]
#[specta::specta]
pub fn open_log_folder(app: AppHandle) -> AppResult<()> {
    use tauri_plugin_opener::OpenerExt;
    let dir = app.path().app_log_dir().map_err(error::window)?;
    local_files::ensure_folder(&dir)?;
    app.opener()
        .open_path(dir.to_string_lossy(), None::<&str>)
        .map_err(|e| local_files::folder_not_opened(&dir, &e))
}

/// Writes text to a path the user picked in a save dialog (e.g. downloaded logs).
#[tauri::command]
#[specta::specta]
pub fn write_text_file(path: String, contents: String) -> AppResult<()> {
    local_files::write_text(Path::new(&path), &contents)
}
