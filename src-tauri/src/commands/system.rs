use serde::Serialize;
use tauri::{AppHandle, Manager, State};

use crate::{
    error::{local_file, AppError, AppResult, ErrorCode},
    services::stacks::compose::{self, ComposeCli},
    state::AppState,
};

#[derive(Debug, Serialize, specta::Type)]
pub struct AppInfo {
    name: String,
    version: String,
    os: &'static str,
    arch: &'static str,
}

#[tauri::command]
#[specta::specta]
pub fn get_app_info(app: AppHandle) -> AppInfo {
    let info = app.package_info();
    AppInfo {
        name: info.name.clone(),
        version: info.version.to_string(),
        os: std::env::consts::OS,
        arch: std::env::consts::ARCH,
    }
}

#[derive(Debug, Serialize, specta::Type)]
pub struct Licenses {
    /// Homeport's own license (`LICENSE`).
    app: &'static str,
    /// Every bundled crate and npm package with its license. Generated by
    /// `bun run licenses` before release builds, so other builds may lack it.
    third_party: Option<String>,
}

#[tauri::command]
#[specta::specta]
pub fn get_licenses(app: AppHandle) -> AppResult<Licenses> {
    let path = app
        .path()
        .resource_dir()?
        .join("licenses/THIRD_PARTY_LICENSES.txt");
    let third_party = match std::fs::read_to_string(path) {
        Ok(text) => Some(text),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.into()),
    };
    Ok(Licenses {
        app: include_str!("../../../LICENSE"),
        third_party,
    })
}

/// What this machine can do; features degrade gracefully when something is missing.
#[derive(Debug, Serialize, specta::Type)]
pub struct Capabilities {
    /// An OS keychain is reachable, so SSH, TLS and stack `.env` secrets can be stored.
    keychain: bool,
    /// The compose CLI used to deploy Managed Stacks, if installed.
    compose: Option<ComposeCli>,
    /// Why there is no usable compose CLI, and how to install one.
    compose_problem: Option<AppError>,
}

#[tauri::command]
#[specta::specta]
pub async fn get_capabilities(state: State<'_, AppState>) -> Result<Capabilities, ()> {
    let (compose, compose_problem) = match compose::detect().await {
        Ok(cli) => (Some(cli), None),
        Err(problem) => (None, Some(problem)),
    };
    Ok(Capabilities {
        keychain: state.secrets.is_available(),
        compose,
        compose_problem,
    })
}

/// Largest file `read_text_file` accepts; certificates and keys are far smaller.
const MAX_TEXT_FILE: u64 = 1024 * 1024;

/// Reads a file the user picked in an open dialog (certificates, keys, compose files).
#[tauri::command]
#[specta::specta]
pub fn read_text_file(path: String) -> AppResult<String> {
    let path = std::path::Path::new(&path);
    let size = std::fs::metadata(path)
        .map_err(|e| local_file(path, e))?
        .len();
    if size > MAX_TEXT_FILE {
        return Err(AppError::new(
            ErrorCode::FileTooLarge,
            format!(
                "{} is too large to be a key, certificate or compose file.",
                path.display()
            ),
        )
        .with_hint("Pick a file under 1 MB."));
    }
    std::fs::read_to_string(path).map_err(|e| local_file(path, e))
}

/// Opens the folder holding Homeport's log files in the file manager.
#[tauri::command]
#[specta::specta]
pub fn open_log_folder(app: AppHandle) -> AppResult<()> {
    use tauri_plugin_opener::OpenerExt;
    let dir = app.path().app_log_dir()?;
    std::fs::create_dir_all(&dir)?;
    app.opener()
        .open_path(dir.to_string_lossy(), None::<&str>)
        .map_err(|e| {
            AppError::new(ErrorCode::Io, "The log folder can't be opened.")
                .with_hint(format!("Open {} in your file manager.", dir.display()))
                .with_cause(&e)
        })
}

/// Writes text to a path the user picked in a save dialog (e.g. downloaded logs).
#[tauri::command]
#[specta::specta]
pub fn write_text_file(path: String, contents: String) -> AppResult<()> {
    let path = std::path::Path::new(&path);
    std::fs::write(path, contents).map_err(|e| local_file(path, e))
}
